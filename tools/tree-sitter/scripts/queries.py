#!/usr/bin/env python3
"""Derive the query copies from queries/*.scm, the nvim-treesitter set.

Neovim, and the tree-sitter CLI's highlighter that runs the assertions
under test/highlight, give a later highlight pattern priority over an
earlier one for the same node; Helix gives the earlier one priority. So
the Helix highlights are the same patterns in reverse order, and every
Helix copy carries Helix's capture names:

- editors/helix/queries/fipe/*.scm.

`--check` exits 1 when a committed copy differs from what this script
derives, without writing.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "queries"

HEADER = (
    "; Generated by scripts/queries.py from queries/{name}; edit that\n"
    "; file and run the script.{order}\n"
)
REVERSED = (
    " Patterns are in reverse order: here\n; the earlier pattern wins."
)

HELIX_HIGHLIGHTS = {
    "boolean": "constant.builtin.boolean",
    "comment": "comment",
    "comment.documentation": "comment.block.documentation",
    "constructor": "constructor",
    "function": "function",
    "function.call": "function",
    "keyword": "keyword",
    "keyword.conditional": "keyword.control.conditional",
    "keyword.import": "keyword.control.import",
    "keyword.modifier": "keyword.storage.modifier",
    "keyword.type": "keyword.storage.type",
    "module": "namespace",
    "number": "constant.numeric.integer",
    "number.float": "constant.numeric.float",
    "operator": "operator",
    "punctuation.bracket": "punctuation.bracket",
    "punctuation.delimiter": "punctuation.delimiter",
    "punctuation.special": "punctuation.special",
    "string": "string",
    "string.special": "string.special",
    "string.special.path": "string.special.path",
    "type": "type",
    "type.definition": "type",
    "variable": "variable",
    "variable.member": "variable.other.member",
    "variable.parameter": "variable.parameter",
}

HELIX_INDENTS = {
    "indent.begin": "indent",
    "indent.branch": "outdent",
}

HELIX_LOCALS = {
    "local.scope": "local.scope",
    "local.reference": "local.reference",
}


def patterns(text):
    """Split a query into its top-level patterns, each with the comment
    lines directly above it. A comment block that a blank line ends (the
    file's header, a section rule) belongs to no pattern and is
    dropped."""
    items, comments, current, depth = [], [], [], 0
    for line in text.split("\n"):
        stripped = line.strip()
        if depth == 0 and not current:
            if stripped.startswith(";"):
                comments.append(line)
                continue
            if not stripped:
                comments = []
                continue
        current.append(line)
        depth += _depth(line)
        if depth == 0:
            items.append((comments, "\n".join(current)))
            comments, current = [], []
    if current:
        raise SystemExit(f"unbalanced query near: {current[0]}")
    return items


def _depth(line):
    depth, in_string, escaped = 0, False, False
    for ch in line:
        if in_string:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
        elif ch == '"':
            in_string = True
        elif ch == ";":
            break
        elif ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
    return depth


def rename(pattern, table, drop=()):
    """Rename every capture by `table`; a capture in `drop` is removed,
    and a pattern left without a capture is dropped (None)."""

    def sub(match):
        name = match.group(1)
        if name in drop:
            return ""
        if name not in table:
            raise SystemExit(f"no mapping for capture @{name}")
        return "@" + table[name]

    out = re.sub(r"@([A-Za-z_.]+)", sub, pattern)
    out = re.sub(r"[ \t]+\n", "\n", out)
    out = re.sub(r"[ \t]+$", "", out)
    if "@" not in out:
        return None
    return out


def derive(name, table=None, drop=(), reverse=False):
    items = patterns((SOURCE / name).read_text())
    out = [HEADER.format(name=name, order=REVERSED if reverse else "")]
    for comments, body in reversed(items) if reverse else items:
        if table is not None:
            body = rename(body, table, drop)
            if body is None:
                continue
        elif drop:
            body = rename(body, _identity(body), drop)
            if body is None:
                continue
        out.append("\n".join(comments + [body]) + "\n")
    return "\n".join(out)


def _identity(body):
    return {n: n for n in re.findall(r"@([A-Za-z_.]+)", body)}


def helix_locals():
    items = patterns((SOURCE / "locals.scm").read_text())
    out = [HEADER.format(name="locals.scm", order="")]
    for comments, body in items:
        body = re.sub(r"@local\.definition\.[a-z]+", "@local.definition", body)
        body = rename(body, {**HELIX_LOCALS, "local.definition": "local.definition"})
        out.append("\n".join(comments + [body]) + "\n")
    return "\n".join(out)


def outputs():
    helix = ROOT / "editors" / "helix" / "queries" / "fipe"
    return {
        helix / "highlights.scm":
            derive("highlights.scm", HELIX_HIGHLIGHTS, drop=("spell",),
                   reverse=True),
        helix / "indents.scm":
            derive("indents.scm", HELIX_INDENTS,
                   drop=("indent.end", "indent.auto")),
        helix / "locals.scm": helix_locals(),
        helix / "injections.scm": derive("injections.scm"),
    }


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in outputs().items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        for path in stale:
            print(f"stale: {path}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
